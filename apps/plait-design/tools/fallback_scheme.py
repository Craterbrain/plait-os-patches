#!/usr/bin/env python3
"""Writes design/src/main/java/app/plait/design/GraphiteScheme.kt: the Material 3 colour roles of the Graphite-blue seed (Tonal
Spot, dark and light), used when the system gives no dynamic colours and in previews. Same algorithm Android runs for a wallpaper.
Run with a Python that has materialyoucolor:  python tools/fallback_scheme.py"""
import os
from materialyoucolor.hct import Hct
from materialyoucolor.scheme.scheme_tonal_spot import SchemeTonalSpot
from materialyoucolor.dynamiccolor.material_dynamic_colors import MaterialDynamicColors as M
SEED = 0xff5b8fcf   # the Graphite blue (the same seed tools/palette.py falls back to in the mocks)
ROLES = ["primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary", "secondary", "onSecondary",
         "secondaryContainer", "onSecondaryContainer", "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
         "background", "onBackground", "surface", "onSurface", "surfaceVariant", "onSurfaceVariant", "surfaceTint",
         "inverseSurface", "inverseOnSurface", "error", "onError", "errorContainer", "onErrorContainer", "outline",
         "outlineVariant", "scrim", "surfaceBright", "surfaceDim", "surfaceContainer", "surfaceContainerHigh",
         "surfaceContainerHighest", "surfaceContainerLow", "surfaceContainerLowest"]
def colours(dark):
    s = SchemeTonalSpot(Hct.from_int(SEED), dark, 0.0)
    out = {}
    for r in ROLES:
        dc = getattr(M, r, None)
        out[r] = (dc.get_hct(s).to_int() & 0xffffff) if dc is not None else None
    out["surfaceTint"] = out["surfaceTint"] if out["surfaceTint"] is not None else out["primary"]
    out["scrim"] = 0x000000
    return out
def block(name, c):
    miss = [k for k, v in c.items() if v is None]
    assert not miss, f"missing roles {miss}"
    return f"internal val {name} = {'darkColorScheme' if 'Dark' in name else 'lightColorScheme'}(\n" + "".join(
        f"    {k} = Color(0xFF{v:06X}),\n" for k, v in c.items()) + ")\n"
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
open(os.path.join(root, "design", "src", "main", "java", "app", "plait", "design", "GraphiteScheme.kt"), "w").write(
    "package app.plait.design\n\nimport androidx.compose.material3.darkColorScheme\nimport androidx.compose.material3.lightColorScheme\n"
    "import androidx.compose.ui.graphics.Color\n\n/* Generated by tools/fallback_scheme.py (Tonal Spot of the Graphite blue). Do not edit. */\n\n"
    + block("GraphiteDark", colours(True)) + "\n" + block("GraphiteLight", colours(False)))
print("ok")
