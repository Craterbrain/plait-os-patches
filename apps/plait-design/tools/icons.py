#!/usr/bin/env python3
"""design/icons.txt -> Android vector drawables (design/src/main/res/drawable/ps_*.xml), PlaitIcon.kt and the mock's
icons.js, from Google's Material Symbols (Rounded, weight 400, 24 dp; Apache License 2.0).

SVGs are fetched once into tools/icon-cache/ (committed, so a rebuild needs no network). A name that does not exist
fails loudly with the list of what failed; nothing is guessed. usage: tools/icons.py [--refresh]"""
import json, os, re, sys, urllib.error, urllib.request
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cache = os.path.join(root, "tools", "icon-cache"); os.makedirs(cache, exist_ok=True)
res = os.path.join(root, "design", "src", "main", "res", "drawable"); os.makedirs(res, exist_ok=True)
BASE = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web/{n}/materialsymbolsrounded/{n}{v}_24px.svg"
refresh = "--refresh" in sys.argv

def fetch(name, fill):
    key = f"{name}{'_fill' if fill else ''}.svg"
    path = os.path.join(cache, key)
    if refresh or not os.path.exists(path):
        url = BASE.format(n=name, v="_fill1" if fill else "")
        with urllib.request.urlopen(url, timeout=30) as r:
            open(path, "wb").write(r.read())
    return open(path).read()

def to_vector(svg, mirror=False):
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
    if not paths: raise ValueError("no path in the SVG")
    m = re.search(r'viewBox="([^"]+)"', svg)
    vb = m.group(1).split() if m else None
    if vb == ["0", "-960", "960", "960"]:      # the usual Material Symbols form: y runs from -960 to 0
        vp, open_g, close_g = 960, '    <group android:translateY="960">\n', "    </group>\n"
    elif vb is None and 'width="24"' in svg and 'height="24"' in svg:   # a few older assets: plain 24 x 24 coordinates
        vp, open_g, close_g = 24, "", ""
    else:
        raise ValueError(f"unexpected viewBox {vb}")
    body = "\n".join(f'        <path\n            android:fillColor="#FF000000"\n            android:pathData="{d}" />' for d in paths)
    return ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/icons.py from Material Symbols (Apache License 2.0). Do not edit. -->\n'
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="24dp"\n    android:height="24dp"\n'
            f'    android:viewportWidth="{vp}"\n    android:viewportHeight="{vp}"\n' + ('    android:autoMirrored="true">\n' if mirror else '    >\n').replace("    >\n", ">\n") + open_g + body + "\n" + close_g + '</vector>\n').replace('"\n>', '">'), paths

want, failed = [], []
for line in open(os.path.join(root, "design", "icons.txt")):
    line = line.split("#")[0].strip()
    if not line: continue
    local, _, rest = line.partition("=")
    parts = [p.strip() for p in rest.split(",")]
    want.append((local.strip(), parts[0], "fill" in parts[1:], "mirror" in parts[1:]))

js, kt, made = {}, [], 0
for local, mat, fill, mirror in want:
    for variant in ([False, True] if fill else [False]):
        out = f"ps_{local}{'_fill' if variant else ''}"
        try:
            xml, paths = to_vector(fetch(mat, variant), mirror)
        except (urllib.error.URLError, ValueError) as e:
            failed.append(f"{local} ({mat}{' fill' if variant else ''}): {e}"); continue
        open(os.path.join(res, out + ".xml"), "w").write(xml)
        js[out] = paths; made += 1
        camel = "".join(w.capitalize() for w in out[3:].split("_"))
        kt.append(f"    val {camel} = R.drawable.{out}")
if failed:
    print("FAILED:\n  " + "\n  ".join(failed)); sys.exit(1)
open(os.path.join(root, "design", "src", "main", "java", "app", "plait", "design", "PlaitIcon.kt"), "w").write(
    "package app.plait.design\n\nimport androidx.annotation.DrawableRes\n\n"
    "/** Generated by tools/icons.py from design/icons.txt (Material Symbols Rounded, Apache License 2.0). Do not edit. */\n"
    "@Suppress(\"unused\")\nobject PlaitIcon {\n" + "\n".join(f"    @get:DrawableRes val {l.split()[1]}: Int get() = {l.split('= ')[1]}" for l in kt) + "\n}\n")
json.dump(js, open(os.path.join(root, "tools", "icons.json"), "w"))
print(f"{made} drawables from {len(want)} icons")
