#!/usr/bin/env python3
"""Plait Backup icon, in the PlaitOS branding: the PlaitOS mark (hexagon holding the silver/amber basketweave, same
geometry and colours as plait-os branding/make_logo.py) inside a circular "history" arrow, the backup/restore sign.

Writes the adaptive-icon layers (ic_launcher_background/foreground/monochrome.xml) to OUTDIR and an SVG preview.
    python3 icon/make-icon.py app/src/main/res/drawable
The monochrome layer is the same drawing in one colour; the over/under gaps are real cuts, so the weave still reads."""
import math
import sys
from pathlib import Path

BG = "#FF0A0D14"                       # PlaitOS card
HEX_FILL = "#FF0E1524"
SILVER, AMBER, RIM, ARROW = "#FFC9D1DD", "#FFFFA21A", "#FFB9C3D2", "#FFE8EDF5"
C = 54.0                               # adaptive icon: 108 x 108, keep the drawing inside the 66 dp safe circle
S = 20 / 240                           # mark scale: circumradius 240 -> 20
N, PITCH, W, GAP, R = 4, 76, 46, 6, 240
RING_R, RING_W = 27.5, 4.2             # the arrow


def f(v):
    return f"{v:.2f}"


def hex_path(r):
    p = [(C + r * S * math.cos(math.radians(a)), C + r * S * math.sin(math.radians(a))) for a in range(-90, 270, 60)]
    return "M" + " L".join(f"{f(x)},{f(y)}" for x, y in p) + " Z"


def rect(x0, y0, w, h):  # in mark units around (0, 0)
    x, y = C + x0 * S, C + y0 * S
    return f"M{f(x)},{f(y)} h{f(w * S)} v{f(h * S)} h{f(-w * S)} Z"


offs = [(i - (N - 1) / 2) * PITCH for i in range(N)]
silver = [rect(-R, y - W / 2, 2 * R, W) for y in offs]
amber = [rect(x - W / 2, -R, W, 2 * R) for x in offs]
gaps_h, gaps_v, over = [], [], []
for r_, y in enumerate(offs):
    for c, x in enumerate(offs):
        if (r_ + c) % 2:
            gaps_h += [rect(x - W / 2 - GAP, y - W / 2, GAP, W), rect(x + W / 2, y - W / 2, GAP, W)]
        else:
            gaps_v += [rect(x - W / 2, y - W / 2 - GAP, W, GAP), rect(x - W / 2, y + W / 2, W, GAP)]
            over.append(rect(x - W / 2, y - W / 2, W, W))


def pt(deg, r):
    a = math.radians(deg)
    return C + r * math.cos(a), C + r * math.sin(a)


# The arrow: a ring open at the top-left, running anticlockwise, with the head at its upper end ("back in time")
A0, A1 = -128, 182                     # start and end angle (degrees, screen coordinates: 0 = right, 90 = down)
x0, y0 = pt(A0, RING_R)
x1, y1 = pt(A1, RING_R)
ring = f"M{f(x0)},{f(y0)} A{RING_R},{RING_R} 0 1 1 {f(x1)},{f(y1)}"
# Arrowhead at the start point, pointing along the direction of travel there (anticlockwise = decreasing angle)
t = math.radians(A0)
tx, ty = math.sin(t), -math.cos(t)     # tangent for decreasing angle
nx, ny = math.cos(t), math.sin(t)      # outward normal
L, Wd = 8.0, 6.2
tip = (x0 + tx * L * 0.75, y0 + ty * L * 0.75)
b1 = (x0 - tx * L * 0.25 + nx * Wd, y0 - ty * L * 0.25 + ny * Wd)
b2 = (x0 - tx * L * 0.25 - nx * Wd, y0 - ty * L * 0.25 - ny * Wd)
head = f"M{f(tip[0])},{f(tip[1])} L{f(b1[0])},{f(b1[1])} L{f(b2[0])},{f(b2[1])} Z"


def layer(mono):
    col = (lambda c: "#FFFFFFFF") if mono else (lambda c: c)
    gap = "#00000000" if mono else HEX_FILL
    p = lambda d, fill: f'        <path android:fillColor="{fill}" android:pathData="{" ".join(d)}" />\n'
    hexfill = "" if mono else f'    <path android:fillColor="{HEX_FILL}" android:pathData="{hex_path(R)}" />\n'
    # In the monochrome layer the gaps must cut the strands: draw the weave without gap fills, but as separate
    # pieces (the under-strand pieces stop at the gap)
    if mono:
        weave = mono_weave()
    else:
        weave = p(silver, SILVER) + p(gaps_h, gap) + p(amber, AMBER) + p(gaps_v, gap) + p(over, SILVER)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Plait Backup icon (generated by icon/make-icon.py) -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
{hexfill}    <group>
        <clip-path android:pathData="{hex_path(R - 14)}" />
{weave}    </group>
    <path android:strokeColor="{col(RIM)}" android:strokeWidth="{f(7 * S * 1.6)}" android:strokeLineJoin="round" android:pathData="{hex_path(R)}" />
    <path android:strokeColor="{col(ARROW)}" android:strokeWidth="{RING_W}" android:strokeLineCap="round" android:pathData="{ring}" />
    <path android:fillColor="{col(ARROW)}" android:pathData="{head}" />
</vector>
"""


def mono_weave():
    """Each strand split into the pieces that are visible: the over-strand whole, the under-strand cut at the gap."""
    pieces = []
    for r_, y in enumerate(offs):           # silver: cut where amber is over
        xs = [-R]
        for c, x in enumerate(offs):
            if (r_ + c) % 2:
                xs += [x - W / 2 - GAP, x + W / 2 + GAP]
        xs.append(R)
        for a, b in zip(xs[0::2], xs[1::2]):
            pieces.append(rect(a, y - W / 2, b - a, W))
    for c, x in enumerate(offs):            # amber: cut where silver is over
        ys = [-R]
        for r_, y in enumerate(offs):
            if (r_ + c) % 2 == 0:
                ys += [y - W / 2 - GAP, y + W / 2 + GAP]
        ys.append(R)
        for a, b in zip(ys[0::2], ys[1::2]):
            pieces.append(rect(x - W / 2, a, W, b - a))
    return f'        <path android:fillColor="#FFFFFFFF" android:pathData="{" ".join(pieces)}" />\n'


out = Path(sys.argv[1] if len(sys.argv) > 1 else ".")
out.mkdir(parents=True, exist_ok=True)
(out / "ic_launcher_background.xml").write_text(f"""<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <path android:fillColor="{BG}" android:pathData="M0,0h108v108h-108z" />
</vector>
""")
(out / "ic_launcher_foreground.xml").write_text(layer(False))
(out / "ic_launcher_monochrome.xml").write_text(layer(True))
print("wrote", out)
